"""Generate the complete declared surface; this is not behavioral FCC evidence."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def inventory(root=ROOT):
    reference = json.loads((root / "kicad_cli/driver_contract.json").read_bytes())["reference"]
    pin = json.loads((root / "kicad_cli/driver_spec/PIN.json").read_bytes())
    return {
        "kind": "complete-declared-public-surface-not-full-FCC",
        "specification": {k: pin[k] for k in ("repository", "version", "commit")},
        "declaration_sha256": hashlib.sha256(
            (root / "kicad_cli/driver_contract.json").read_bytes()
        ).hexdigest(),
        "runtime": (
            "Except exact dependency-free root bootstrap forms, all command paths and "
            "argument combinations use the pinned driver parser."
        ),
        "syntax": {
            "order": "command path, then named flags; no positional input values",
            "booleans": "bare flag or =true/=false; no 1/0 or separate values",
            "repetition": (
                "Command scalars reject repeated flags. The generic multiple-value parser "
                "expands CSV/repeated inputs and retains first occurrences; JSON array text "
                "is not a generic list input. Command "
                "constraints apply before that generic deduplication: power-task nets/classes "
                "and plot/Gerber layers reject repeated names. Distinct layer aliases that "
                "resolve to the same layer also refuse. Global booleans/format use the last "
                "effective value. Read each command's selection constraints."
            ),
            "version": "root --version only; authenticated runtime required",
            "help": (
                reference["dependency_configuration"]["bootstrap"]["root_help"]
            ),
            "query": "fields projects top-level data, never reduces computation",
            "write": (
                "scope plus dry-run, inspect preview, identical parameters plus confirm; "
                "token is not authorization"
            ),
            "zero_write": (
                "Refusal means protected engineering inputs/outputs unchanged; previews and "
                "queries may create owned state/evidence/configuration. "
                "Inspect explicit test boundaries."
            ),
        },
        "global_options": reference["global_options"],
        "commands": sorted(reference["commands"], key=lambda c: c["path"]),
        "schemas": reference["schemas"],
        "json_schemas": reference["json_schemas"],
        "dependency_configuration": reference["dependency_configuration"],
        "release_readiness": reference["release_readiness"],
        "error_codes": reference["error_codes"],
        "exit_codes": reference["exit_codes"],
    }


def cell(value):
    return json.dumps(value, ensure_ascii=False, separators=(",", ":")).replace("|", "\\|")


def markdown(data):
    commands = data["commands"]
    lines = [
        "# Public command and parameter inventory",
        "",
        "Generated by `python -B scripts/public_surface.py`; do not edit by hand.",
        "The adjacent PUBLIC_COMMANDS.json retains every declaration, "
        "schema, dependency and error rule.",
        f"Inventory: {len(commands)} paths, "
        f"{sum(len(c['params']) for c in commands)} command parameters, "
        f"{len(data['global_options'])} global options. "
        "This is **not full FCC** or a semantic pass claim.",
        "Test/run/source/EXE bindings belong to the separate execution ledger; "
        "source parser audits, EXE refusals, native checks and engineering acceptance "
        "are distinct.",
        "",
        "Pinned driver specification: " + cell(data["specification"]),
        "",
        "## Syntax and global options",
        "",
    ]
    lines += ["- " + value for value in data["syntax"].values()]

    def table(params):
        rows = [
            "",
            "| Flag | Type | Required | Multiple | Default (literal or derived) "
            "| Constraints / meaning |",
            "|---|---|---|---|---|---|",
        ]
        for p in params:
            extra = {
                k: v
                for k, v in p.items()
                if k not in {"name", "type", "required", "multiple", "default", "default_from"}
            }
            default = {k: p[k] for k in ("default", "default_from") if k in p}
            rows.append(
                "| "
                + " | ".join(
                    [
                        "`--" + p["name"] + "`",
                        p["type"],
                        str(p["required"]).lower(),
                        str(p["multiple"]).lower(),
                        cell(default),
                        cell(extra),
                    ]
                )
                + " |"
            )
        return rows + [""]

    lines += table(data["global_options"])
    for command in commands:
        driver = command["driver"]
        lines += [
            "## " + command["path"],
            "",
            command["description"],
            "",
            f"Type: {command['type']}; effects: {cell(driver['effects'])}; "
            f"phases: {cell(driver['phases'])}; modes: {cell(driver['modes'])}.",
            f"Dangerous: {cell(command.get('dangerous', False))}; "
            f"recovery: {cell(driver['recovery'])}.",
            "Authorization: "
            + (
                "user-granted scope, preview/confirm; dangerous consent if declared."
                if command["type"] == "write"
                else "read/discovery; operation resolve requires "
                "the existing recovery contract and evidence."
            ),
            "Output schema: `"
            + command["output_schema"]
            + "`; profiles: "
            + cell(driver["profiles"])
            + ".",
            "",
        ]
        lines += table(command["params"])
        for key in ("required_any", "constraints"):
            if command.get(key):
                lines += [key + ": " + cell(command[key]), ""]
        if command.get("selection_schema"):
            lines += [
                "Selection constraints: " + command["selection_constraints"],
                "",
                "Expanded-selection review schema: `" + command["selection_schema"] + "`.",
                "This describes selection tokens after CSV/repeated-input expansion, not a new CLI "
                "input format. The runtime also checks board-dependent identities.",
                "",
            ]
        if command.get("routing_constraint_schema"):
            lines += [
                "Routing constraint witness schema: `"
                + command["routing_constraint_schema"]
                + "`.",
                "This describes `preview.extensions.smd_drill_clearance` and its saved receipt "
                "copy. It is a finite planner constraint, separate from independent native DRC "
                "and physical connectivity acceptance.",
                "",
            ]
        if command.get("via_hole_spacing_schema"):
            lines += [
                "Via-hole spacing witness schema: `" + command["via_hole_spacing_schema"] + "`.",
                "This describes the grid candidate's executed "
                "`preview.extensions.via_hole_spacing` "
                "and its receipt copy. The finite project rule binds actual drill edges across "
                "retained and newly planned vias, independent of net; official DRC stays separate.",
                "",
            ]
        if command.get("candidate_review_schema"):
            lines += [
                "Pre-confirm candidate review schema: `"
                + command["candidate_review_schema"]
                + "`.",
                "Only an explicit `--candidate-out` materializes the exact scoped PCB bytes. "
                "Read `preview.extensions.candidate_review` for the public path, signed manifest, "
                "source/companion identities and original confirmation validity. Independent "
                "images must bind candidate/hash/layers/mirror/renderer configuration and "
                "any companion path relocations.",
                "",
            ]
        lines += ["Limits:", ""] + ["- " + limit for limit in driver["limits"]] + [""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = inventory()
    files = {
        ROOT / "docs/PUBLIC_COMMANDS.json": json.dumps(data, ensure_ascii=False, indent=2) + "\n",
        ROOT / "docs/PUBLIC_COMMANDS.md": markdown(data),
    }
    for path, content in files.items():
        if args.check:
            if path.read_text(encoding="utf-8") != content:
                raise SystemExit("Stale generated surface: " + str(path))
        else:
            path.write_text(content, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
