def test_each_module_has_concrete_unexecuted_agent_scenarios():
    scenarios = EVALS["modules"]
    assert set(scenarios) == set(MODULES)
    common = EVALS["common"]
    assert len(common) == 9
    readonly = next(case for case in common if "只检查" in case["prompt"])
    assert readonly["modules"] == ["kicad-review"] and not readonly["may_write_when_authorized"]
    for module, cases in scenarios.items():
        assert len(cases) >= 3
        prompts = common + cases
        assert len({case["id"] for case in prompts}) == len(prompts)
        assert all(case["prompt"] and case["expected"] for case in prompts)
        assert all(case["agent_evaluation"] == "not_run" for case in prompts)
        assert all(case["modules"] == [module] for case in cases)
    assert {case["scenario"] for case in scenarios["kicad-pcb"]} >= {
        "read-only-diagnostics",
        "authorized-straight-patch",
        "exact-duplicate-cleanup",
        "missing-project-rules",
        "invalid-endpoint",
        "plane-preservation-conflict",
        "identity-repair",
        "unknown-outcome",
        "locked-copper",
    }


@pytest.mark.parametrize("name", list(MODULES))
def test_regeneration_removes_retired_eval_input(name, tmp_path):
    from scripts.build_module_skills import INSTALL_NAMES, generate

    folder = tmp_path / INSTALL_NAMES[name]
    folder.mkdir()
    retired = folder / "test-prompts.json"
    retired.write_text('[{"agent_evaluation":"not_run"}]', encoding="utf-8")
    (folder / "RESOURCE-MANIFEST.json").write_text(
        json.dumps({retired.name: hashlib.sha256(retired.read_bytes()).hexdigest()}),
        encoding="utf-8",
    )
    generate(tmp_path, name)
    assert not retired.exists()
    manifest = json.loads((folder / "RESOURCE-MANIFEST.json").read_bytes())
    assert retired.name not in manifest


def test_skill_generation_needs_no_developer_eval_tree(tmp_path, monkeypatch):
    import shutil

    from scripts import build_module_skills

    source = tmp_path / "source"
    for name in ("docs/modules", "knowledge"):
        shutil.copytree(ROOT / name, source / name)
    shutil.copyfile(ROOT / "docs/KNOWLEDGE.md", source / "docs/KNOWLEDGE.md")
    shutil.copyfile(ROOT / "LICENSE", source / "LICENSE")
    monkeypatch.setattr(build_module_skills, "ROOT", source)
    build_module_skills.generate(tmp_path / "skills")
    assert not (source / "tests").exists()
    assert not list((tmp_path / "skills").rglob("test-prompts.json"))


def test_generated_skill_resources_are_current(tmp_path):
    from scripts.build_module_skills import INSTALL_NAMES, generate

    generate(tmp_path)
    for install_name in INSTALL_NAMES.values():
        fresh = tmp_path / install_name
        checked = ROOT / "skills" / install_name
        manifest = json.loads((fresh / "RESOURCE-MANIFEST.json").read_bytes())
        assert list(manifest) == sorted(manifest), "Manifest key order must be OS-independent"
        assert {p.relative_to(fresh) for p in fresh.rglob("*") if p.is_file()} == {
            p.relative_to(checked) for p in checked.rglob("*") if p.is_file()
        }
        for path in fresh.rglob("*"):
            if path.is_file():
                assert path.read_bytes() == (checked / path.relative_to(fresh)).read_bytes()
